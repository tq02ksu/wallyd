#!/usr/bin/env python3
"""Copy the hardware-free pure core out of the speech bridge script.

`scripts/mac_speech.swift` is a single-file Swift script: its top-level code
dispatches CLI modes, so it only compiles when it is the main file and a Swift
package cannot import it. Rather than maintain a copy that silently drifts, the
macOS CI lane extracts the two declarations that need no AVFoundation device:

  * ``struct EnergyVAD``     -- energy VAD (debounce, hysteresis, endpointing)
  * ``func splitSentences``  -- TTS sentence splitting and length bounding

Both are real production logic used by the bridge; neither touches a
microphone, speaker, camera, or TCC permission, which is why the macOS CI runner
can execute them. If either declaration is renamed or removed, this script
fails, which turns the ``apple`` lane red instead of quietly testing nothing.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

DECLARATIONS = ("struct EnergyVAD {", "func splitSentences(")

HEADER = """\
// Generated by scripts/apple/extract_bridge_core.py -- do not edit.
// Source of truth: scripts/mac_speech.swift (GH-36 apple lane).
import Foundation
"""


class ExtractError(RuntimeError):
    pass


def _block_end(text: str, start: int) -> int:
    """Return the index just past the body of the block starting at ``start``.

    Tracks line comments, block comments, and string literals so braces in
    diagnostics or messages cannot unbalance the brace counter.
    """
    try:
        i = text.index("{", start)
    except ValueError as exc:  # pragma: no cover - guarded by DECLARATIONS
        raise ExtractError(f"no opening brace after offset {start}") from exc

    depth = 0
    length = len(text)
    while i < length:
        char = text[i]
        if char == "/" and text.startswith("//", i):
            newline = text.find("\n", i)
            if newline < 0:
                break
            i = newline
            continue
        if char == "/" and text.startswith("/*", i):
            end = text.find("*/", i + 2)
            if end < 0:
                raise ExtractError("unterminated block comment")
            i = end + 2
            continue
        if char == '"':
            i += 1
            while i < length:
                if text[i] == "\\":
                    i += 2
                    continue
                if text[i] == '"':
                    i += 1
                    break
                i += 1
            continue
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ExtractError("unterminated block")


def extract(source: str) -> str:
    blocks = []
    for declaration in DECLARATIONS:
        start = source.find(declaration)
        if start < 0:
            raise ExtractError(f"declaration not found: {declaration!r}")
        end = _block_end(source, start)
        blocks.append(source[start:end])

    parts = [HEADER]
    for block in blocks:
        parts.append("\n" + block + "\n")
    return "".join(parts)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", required=True, type=Path, help="mac_speech.swift")
    parser.add_argument("--out", required=True, type=Path, help="generated Swift file")
    args = parser.parse_args(argv)

    try:
        source = args.source.read_text(encoding="utf-8")
        generated = extract(source)
    except (OSError, ExtractError) as exc:
        print(f"[extract_bridge_core] {exc}", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(generated, encoding="utf-8")
    print(f"[extract_bridge_core] wrote {args.out} ({len(generated)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
